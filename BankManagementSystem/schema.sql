-- ── Step 1: Create the database if it doesn't already exist ─────────────────
-- We use IF NOT EXISTS so running this file twice never causes an error.
CREATE DATABASE IF NOT EXISTS bank_management
    CHARACTER SET utf8mb4        -- supports all Unicode characters
    COLLATE utf8mb4_unicode_ci;  -- case-insensitive comparisons

-- Switch to this database for all following statements
USE bank_management;


-- ── Step 2: Create the accounts table ───────────────────────────────────────
CREATE TABLE IF NOT EXISTS accounts (

    -- Primary key: generated by Python as "ACC00000001", "ACC00000002", etc.
    account_number  VARCHAR(12)     NOT NULL,

    -- Customer details — all required at account creation time
    customer_name   VARCHAR(100)    NOT NULL,
    phone           VARCHAR(15)     NOT NULL,
    address         VARCHAR(255)    NOT NULL,

    -- DECIMAL(12,2) stores exact monetary values like 9999999999.99
    -- A plain FLOAT would cause rounding errors — never use FLOAT for money!
    balance         DECIMAL(12,2)   NOT NULL DEFAULT 0.00,

    -- Auto-set by MySQL when the row is inserted
    created_at      DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Soft-delete pattern: we never DELETE rows, we just set status='inactive'
    -- This preserves the account record and all its transaction history.
    status          ENUM('active', 'inactive') NOT NULL DEFAULT 'active',

    -- ── Constraints ───────────────────────────────────────────────────────
    CONSTRAINT pk_accounts  PRIMARY KEY (account_number),

    -- Database-level guard: balance can never go below zero
    CONSTRAINT chk_balance  CHECK (balance >= 0.00)
);


-- ── Step 3: Create the transactions table ───────────────────────────────────
CREATE TABLE IF NOT EXISTS transactions (

    -- Auto-increment integer: MySQL assigns 1, 2, 3, ... automatically
    transaction_id   INT             NOT NULL AUTO_INCREMENT,

    -- Which account does this transaction belong to?
    account_number   VARCHAR(12)     NOT NULL,

    -- Only two valid types; ENUM enforces this at the database level
    transaction_type ENUM('deposit', 'withdrawal') NOT NULL,

    -- Amount is always stored as a positive number.
    -- The direction (in/out) is captured by transaction_type above.
    amount           DECIMAL(12,2)   NOT NULL,

    -- Auto-set by MySQL at insert time
    transaction_date DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Optional human-readable note, e.g. "Opening deposit", "ATM withdrawal"
    description      VARCHAR(255)    DEFAULT NULL,

    -- ── Constraints ───────────────────────────────────────────────────────
    CONSTRAINT pk_transactions  PRIMARY KEY (transaction_id),

    -- Foreign key: links each transaction to a valid account.
    -- ON DELETE RESTRICT  → prevents deleting an account that has transactions.
    -- ON UPDATE CASCADE   → if account_number ever changes, it updates here too.
    CONSTRAINT fk_account       FOREIGN KEY (account_number)
                                REFERENCES accounts (account_number)
                                ON DELETE RESTRICT
                                ON UPDATE CASCADE,

    -- Amount must always be positive
    CONSTRAINT chk_amount       CHECK (amount > 0.00),

    -- ── Indexes ──────────────────────────────────────────────────────────
    -- Speeds up "show all transactions for account X" queries
    INDEX idx_account_number    (account_number),

    -- Speeds up date-range queries and ORDER BY transaction_date DESC
    INDEX idx_transaction_date  (transaction_date)
);


